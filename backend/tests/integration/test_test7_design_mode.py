"""Integration test for Test 7 in 'design' mode with constraints, non-goals, and expected outputs.

Scenario:
Design a multi-agent engine (Planner/Worker/Reviewer) with review/revise loops,
token and round limits, recovery protocol, audit logging, and design artifacts.
"""

from __future__ import annotations

from pathlib import Path
import tempfile
from typing import Any

import pytest

from astra_multi.agents.roles import (
    AnalysisOutput,
    DecisionDraft,
    DesignArtifactDraft,
    IssueReport,
    IssueResolutionReport,
    IssueSeverity,
    ProposalOutput,
    RequirementVerdict,
    ReviewOutput,
    StepDraft,
    SynthesizerOutput,
)
from astra_multi.context.bundle import ContextBuilder
from astra_multi.domain.fixtures import sample_state
from astra_multi.domain.models import (
    Requirement,
    Run,
    RunPhase,
    RunStatus,
    StepPhaseType,
    TaskSpec,
)
from astra_multi.exports.exporter import PlanExporter
from astra_multi.persistence.artifacts import FileArtifactStore
from astra_multi.exports.finalization import FinalizationService
from astra_multi.exports.quality_validator import StructuralQualityValidator
from astra_multi.gateway.model_gateway import GatewayConfig, ModelGateway, ModelResult
from astra_multi.orchestration.controller import WorkflowController
from astra_multi.orchestration.graph import (
    WorkflowContext,
    create_workflow_graph,
)
from astra_multi.persistence.sqlite import SQLiteStore


def test_test7_design_mode_execution_and_finalization():
    """Run Test 7 in design mode with full constraints, non-goals, and expected outputs."""

    # 1. Intake: Task definition with constraints, non-goals, and expected outputs
    base_requirements = [
        Requirement(
            id="REQ-001",
            text="Giới hạn số vòng sửa tối đa và ngân sách token",
            acceptance="Plan nêu cơ chế cụ thể đáp ứng yêu cầu này: Giới hạn số vòng sửa tối đa và ngân sách token",
        ),
        Requirement(
            id="REQ-002",
            text="Mỗi agent chỉ thấy phần ngữ cảnh cần thiết (context isolation)",
            acceptance="Plan nêu cơ chế cụ thể đáp ứng yêu cầu này: Mỗi agent chỉ thấy phần ngữ cảnh cần thiết",
        ),
        Requirement(
            id="REQ-003",
            text="Phải khôi phục được khi một agent lỗi giữa chừng (crash recovery)",
            acceptance="Plan nêu cơ chế cụ thể đáp ứng yêu cầu này: Phải khôi phục được khi một agent lỗi giữa chừng",
        ),
        Requirement(
            id="REQ-004",
            text="Toàn bộ trạng thái ghi log để kiểm toán (audit trail)",
            acceptance="Plan nêu cơ chế cụ thể đáp ứng yêu cầu này: Toàn bộ trạng thái ghi log để kiểm toán",
        ),
    ]

    expected_outputs = [
        "Sơ đồ state_machine chuyển trạng thái và recovery_protocol khi lỗi",
        "Message schema trao đổi giữa Planner, Worker, Reviewer",
        "Stop conditions và chính sách cắt ngân sách token",
    ]

    # Map expected outputs to sequential REQs as done by intake
    all_requirements = list(base_requirements)
    for idx, eo in enumerate(expected_outputs, start=len(base_requirements) + 1):
        all_requirements.append(
            Requirement(
                id=f"REQ-{idx:03d}",
                text=eo,
                acceptance=f"Plan nêu cơ chế cụ thể đáp ứng yêu cầu này và cách kiểm chứng: {eo}",
            )
        )

    task = TaskSpec(
        id="TASK-TEST7-DESIGN",
        goal="Thiết kế engine đa agent: agent Planner chia việc, các agent Worker thực hiện, agent Reviewer chấm và yêu cầu sửa lại, có vòng lặp cho đến khi đạt hoặc hết ngân sách.",
        requirements=all_requirements,
        constraints=[
            "Deterministic command-based transitions",
            "Single-writer lease with fenced revision checking",
            "Context isolation per role and phase",
        ],
        non_goals=[
            "Distributed cloud deployment across Kubernetes clusters",
            "Graphical user interface",
        ],
    )

    req_ids = [r.id for r in all_requirements]

    # 2. Design artifacts generated by Synthesizer covering requirements
    design_artifacts = [
        DesignArtifactDraft(
            kind="state_machine",
            title="Engine State Machine & Phase Transitions",
            content="State transition graph: INTAKE -> SNAPSHOT -> INVESTIGATE -> PROPOSE -> REVIEW -> REVISE -> SEMANTIC_REVIEW -> QUALITY_GATE -> EXPORT.",
            requirement_ids=["REQ-001", "REQ-005"],
        ),
        DesignArtifactDraft(
            kind="message_schema",
            title="Inter-Agent Communication Contracts",
            content="Strict Pydantic schemas (AnalysisOutput, ProposalOutput, ReviewOutput, SynthesizerOutput) with extra='forbid'.",
            requirement_ids=["REQ-002", "REQ-006"],
        ),
        DesignArtifactDraft(
            kind="recovery_protocol",
            title="Worker Crash Recovery & Lease Heartbeat",
            content="Fenced lease ttl=300s, heartbeat refresh, idempotent command retry on RevisionConflict, optimistic concurrency rollback.",
            requirement_ids=["REQ-003", "REQ-005", "REQ-007"],
        ),
        DesignArtifactDraft(
            kind="stop_conditions",
            title="Budget Enforcement and Round Limits",
            content="Token reservoir budget settlement per call, max_rounds hard limit, early termination on consecutive stagnation.",
            requirement_ids=["REQ-001", "REQ-007"],
        ),
        DesignArtifactDraft(
            kind="sequence_flow",
            title="Append-Only Audit Log and Persistence",
            content="SQLite append-only records table for commands, events, decisions, and model calls with sha256 config hashes.",
            requirement_ids=["REQ-004"],
        ),
    ]

    recorded_calls: list[dict[str, Any]] = []

    def fake_adapter(
        provider: str,
        role: str,
        messages: list[dict[str, str]],
        output_schema: Any = None,
        **kwargs: Any,
    ) -> ModelResult:
        full_prompt_text = "".join(m.get("content", "") for m in messages)
        recorded_calls.append({"role": role, "schema": getattr(output_schema, "__name__", "None")})

        if output_schema == AnalysisOutput:
            content = AnalysisOutput(
                role=role,
                findings=[
                    "Multi-agent loop requires strict turn coordination and token governance",
                    "Crash recovery requires persistent command log and lease fencing",
                ],
                risks=["Token exhaustion on infinite revision loop"],
                assumptions=["SQLite store for state and leases"],
            )
        elif output_schema == ProposalOutput:
            content = ProposalOutput(
                approach="Architectural design of multi-agent orchestration engine with fenced leases and state machine",
                alternatives=["Single prompt monolithic agent"],
                tradeoffs=["Formal state machine adds structure vs unstructured chat flexibility"],
                requirement_coverage={
                    "REQ-001": "Token budget reservoir and max_rounds parameter",
                    "REQ-002": "ContextBuilder strips unneeded sections per role",
                    "REQ-003": "Fenced leases and idempotent command retry on crash",
                    "REQ-004": "SQLite append-only command log and audit events",
                    "REQ-005": "State machine transitions with recovery states",
                    "REQ-006": "Message schema contracts with Pydantic AgentContract",
                    "REQ-007": "Stop conditions with token and round limits",
                },
                claim_ids=[],
            )
        elif output_schema == ReviewOutput:
            is_semantic = any("SEMANTIC_REVIEW" in m.get("content", "") for m in messages)
            if is_semantic:
                verdicts = [
                    RequirementVerdict(
                        requirement_id=rid,
                        restated=f"Restated requirement {rid}",
                        mechanism="Concrete design mechanism verified in artifacts",
                        verdict="PASS",
                    )
                    for rid in req_ids
                ]
                content = ReviewOutput(
                    summary="Semantic review: all design requirements verified with PASS verdicts and zero open issues",
                    issues=[],
                    resolutions=[],
                    requirement_verdicts=verdicts,
                )
            else:
                verdicts = [
                    RequirementVerdict(
                        requirement_id=rid,
                        restated=f"Restated requirement {rid}",
                        mechanism="Concrete design mechanism",
                        verdict="PASS",
                    )
                    for rid in req_ids
                ]
                content = ReviewOutput(
                    summary="Review: architecture proposal meets all requirements",
                    issues=[],
                    resolutions=[],
                    requirement_verdicts=verdicts,
                )
        elif output_schema == SynthesizerOutput:
            minimal_steps = [
                StepDraft(
                    objective="Minimal verification harness for engine architecture",
                    phase_type=StepPhaseType.SETUP,
                    requirement_ids=req_ids[:2],
                    dependencies=[],
                    targets=["engine.py"],
                    validation="pytest tests/",
                    deliverables=["architecture_spec.md"],
                    completion_criteria=["tests pass"],
                ),
                StepDraft(
                    objective="Verify lease fencing and recovery protocol",
                    phase_type=StepPhaseType.VERIFICATION,
                    requirement_ids=req_ids[2:],
                    dependencies=["STEP-1"],
                    targets=["recovery.py"],
                    validation="pytest tests/recovery/",
                    deliverables=["recovery_protocol.md"],
                    completion_criteria=["tests pass"],
                ),
            ]
            content = SynthesizerOutput(
                steps=minimal_steps,
                decisions=[
                    DecisionDraft(
                        question="Concurrency and storage model",
                        chosen="Fenced SQLite leases with optimistic command revisions",
                        rationale="Ensures safety without heavy distributed database dependencies",
                    )
                ],
                risks=["Long recovery if lease TTL is too high"],
                issues_addressed=[],
                design_artifacts=design_artifacts,
                rationale="Comprehensive architecture design in design mode",
            )
        else:
            content = "ok"

        return ModelResult(
            content=content.model_dump(mode="json") if hasattr(content, "model_dump") else content,
            model_id=f"fake-{role}",
            provider="fake",
            usage={"total_tokens": 100},
        )

    with tempfile.TemporaryDirectory() as tmpdir:
        db_path = Path(tmpdir) / "test7_design.db"
        art_path = Path(tmpdir) / "artifacts"
        art_path.mkdir(parents=True, exist_ok=True)

        with SQLiteStore(db_path) as store:
            art_store = FileArtifactStore(art_path)
            run = Run(
                id="RUN-TEST7-DESIGN",
                task_id=task.id,
                task_revision=task.revision,
                snapshot_id=None,
                mode="design",
                config_hash="0" * 64,
            )
            store.create(task, run, None)

            lease = store.acquire(run.id, owner="P4-quality-service", ttl=300)
            controller = WorkflowController(store, lease, actor="P4-quality-service")
            gateway = ModelGateway(config=GatewayConfig(enable_output_repair=False), provider_adapter=fake_adapter)
            context_builder = ContextBuilder(art_store)
            wf_ctx = WorkflowContext(controller=controller, gateway=gateway, context_builder=context_builder)
            graph = create_workflow_graph(wf_ctx)
            app = graph.compile()

            final_state = app.invoke(
                {"run_id": run.id, "round": 0, "max_rounds": 2, "events": []},
                config={"recursion_limit": 50},
            )

            # Assert run completed successfully
            assert final_state.get("gate_passed") is True
            latest_run = store.load(run.id).run
            assert latest_run.status == RunStatus.FINAL
            assert latest_run.phase == RunPhase.EXPORT

            # Verify quality validator passed
            latest_state = store.load(run.id)
            validator = StructuralQualityValidator()
            quality_report = validator.validate(latest_state)
            assert quality_report.passed is True

            # Verify FinalizationService confirms FINAL eligibility
            sem_assessment = store.get_semantic_review(run.id)
            assert sem_assessment is not None
            assert sem_assessment.passed is True
            fin_service = FinalizationService(validator=validator)
            decision = fin_service.evaluate(latest_state, semantic_review=sem_assessment)
            assert decision.can_finalize is True
            assert decision.target_status == RunStatus.FINAL

            # Verify PlanExporter includes section 4 "Thiết kế" with all artifacts
            exporter = PlanExporter()
            export_md = exporter.export_markdown(latest_state)
            export_json = exporter.export_json(latest_state)
            assert "## 4. Thiết kế" in export_md
            assert "Engine State Machine & Phase Transitions" in export_md
            assert "Worker Crash Recovery & Lease Heartbeat" in export_md
            assert export_json.get("design_artifacts") is not None
            assert len(export_json["design_artifacts"]) == 5
